import { act, cleanup, fireEvent, render, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import App from '../../App'

afterEach(() => {
  cleanup()
  vi.restoreAllMocks()
  localStorage.removeItem('elevSubway.departureMinutes.v1')
  act(() => { void window.AuthService.logout() })
})
type Result = Record<string, unknown>
const result = (leaveAt: string): Result => ({ leaveAt, boardAt: '10:00', arriveAt: '10:30', live: true, route: {}, elevatorWarnings: [], limitations: [], warningStatus: 'UNCONFIRMED' })
const open = (destId = 'gangnam') => act(() => { (window.App!.openTime as (o: object) => void)({ originId: 'sindorim', destId, arriveBy: null }) })
const deferred = () => { let resolve!: (r: Result) => void; const promise = new Promise<Result>((r) => { resolve = r }); return { promise, resolve } }

it('API 응답 순서가 뒤집혀도 마지막 계산 결과를 유지한다', async () => {
  const first = deferred(), second = deferred()
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
  render(<App />)
  open()
  await waitFor(() => expect(calculate).toHaveBeenCalledTimes(1))
  open('gyodae')
  await waitFor(() => expect(calculate).toHaveBeenCalledTimes(2))
  await act(async () => second.resolve(result('09:20')))
  expect(document.querySelector('#timeResult .big-time')!.textContent).toContain('9:20')
  await act(async () => first.resolve(result('08:10')))
  expect(document.querySelector('#timeResult .big-time')!.textContent).toContain('9:20')
})

it('같은 역으로 새 계산을 요청하면 이전 응답을 버리고 로딩을 해제한다', async () => {
  const pending = deferred()
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockReturnValue(pending.promise)
  render(<App />)
  open()
  await waitFor(() => expect(calculate).toHaveBeenCalledOnce())
  open('sindorim')
  await act(async () => pending.resolve(result('08:10')))
  expect(document.querySelector('#timeResult .big-time')).toBeNull()
  expect(document.querySelector('#timeResult')!.textContent).toContain('같아요')
  expect((document.querySelector('#timeForm button[type="submit"]') as HTMLButtonElement).disabled).toBe(false)
})

it('API 실패는 오류로 표시하고 mock 계산으로 넘어가지 않는다', async () => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockRejectedValue({ code: 'NETWORK' })
  const mock = vi.spyOn(window.TimeCalculator, 'calculateDeparture')
  vi.spyOn(console, 'error').mockImplementation(() => {})
  render(<App />)
  open()
  await waitFor(() => expect(document.querySelector('#timeResult [role="alert"]')).not.toBeNull())
  expect(mock).not.toHaveBeenCalled()
  expect(document.querySelector('#timeResult')!.textContent).toContain('연결')
})

// 예상 이동 시간은 마이페이지에서 정하고 저장한다 (#87). 출발계산은 저장값(로그인 시) 또는 기본값을 쓴다.
const goTab = (tab: string) => act(() => { window.App!.switchTab(tab) })
const editMinute = (id: string, value: string) => fireEvent.change(document.getElementById(id)!, { target: { value } })
const saveMinutes = () => fireEvent.click(Array.from(document.querySelectorAll('#departureSettings button')).find((b) => b.textContent === '저장')!)
const loginMypage = () => { act(() => { window.AuthService.login('google') }); goTab('login') }

it('마이페이지에서 저장한 예상 이동 시간을 API 계산에 전달하고 openTime에서도 유지한다', async () => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockResolvedValue(result('09:20'))
  render(<App />)
  loginMypage()
  editMinute('walkToStationMinutes', '18')
  editMinute('stationEntryMinutes', '9')
  editMinute('exitWalkMinutes', '12')
  editMinute('bufferMinutes', '15')
  saveMinutes()
  expect(localStorage.getItem('elevSubway.departureMinutes.v1')).not.toBeNull()
  goTab('time')
  open()
  await waitFor(() => expect(calculate).toHaveBeenCalledOnce())
  expect(calculate.mock.calls[0][0]).toMatchObject({ walkToStationMinutes: 18, stationEntryMinutes: 9, exitWalkMinutes: 12, bufferMinutes: 15 })
  open('gyodae')
  await waitFor(() => expect(calculate).toHaveBeenCalledTimes(2))
  expect(calculate.mock.calls[1][0]).toMatchObject({ walkToStationMinutes: 18, stationEntryMinutes: 9, exitWalkMinutes: 12, bufferMinutes: 15 })
})

it('비로그인 사용자는 저장값이 있어도 기본값으로 계산한다', () => {
  localStorage.setItem('elevSubway.departureMinutes.v1', JSON.stringify({ version: 1, walkToStationMinutes: 40, stationEntryMinutes: 3, exitWalkMinutes: 3, bufferMinutes: 5 }))
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(false)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDeparture').mockReturnValue({ ...result('09:20'), live: false })
  render(<App />)
  open()
  expect(calculate.mock.lastCall?.[0]).toMatchObject({ walkToStationMinutes: 10, stationEntryMinutes: 5, exitWalkMinutes: 5, bufferMinutes: 10 })
})

it('잘못된 예상 시간은 저장하지 않고 마이페이지에서 안내한다', () => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(false)
  render(<App />)
  loginMypage()
  editMinute('walkToStationMinutes', '121')
  saveMinutes()
  expect(localStorage.getItem('elevSubway.departureMinutes.v1')).toBeNull()
  expect(document.getElementById('walkToStationMinutes')?.getAttribute('aria-invalid')).toBe('true')
  expect(document.getElementById('walkToStationMinutesError')?.textContent).toBeTruthy()
})

it('예상 시간을 저장하면 계산 중이던 이전 API 응답을 버린다', async () => {
  const pending = deferred()
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockReturnValue(pending.promise)
  render(<App />)
  open()
  await waitFor(() => expect(calculate).toHaveBeenCalledOnce())
  loginMypage()
  editMinute('bufferMinutes', '15')
  saveMinutes()
  goTab('time')
  await act(async () => pending.resolve(result('08:10')))
  expect(document.querySelector('#timeResult .big-time')).toBeNull()
  expect(document.getElementById('timeResult')?.textContent).toContain('다시 계산')
  expect((document.querySelector('#timeForm button[type="submit"]') as HTMLButtonElement).disabled).toBe(false)
})

it('저장값을 지우면 자동 예상 시간(기본값)으로 계산한다', () => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(false)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDeparture').mockReturnValue({ ...result('09:20'), live: false })
  render(<App />)
  loginMypage()
  editMinute('walkToStationMinutes', '0')
  saveMinutes()
  goTab('time')
  open()
  expect(calculate.mock.lastCall?.[0]).toMatchObject({ walkToStationMinutes: 0 })
  goTab('login')
  fireEvent.click(Array.from(document.querySelectorAll('#departureSettings button')).find((b) => b.textContent === '저장값 지우고 기본값 쓰기')!)
  goTab('time')
  open()
  expect(calculate.mock.lastCall?.[0]).toMatchObject({ walkToStationMinutes: 10, stationEntryMinutes: 5, exitWalkMinutes: 5, bufferMinutes: 10 })
})

it('출발계산 화면은 개인 설정 UI 없이 현재 예상 시간과 로그인 안내 문구만 보여 준다', () => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(false)
  render(<App />)
  open()
  expect(document.getElementById('departureMinutes')).toBeNull()
  expect(document.querySelector('[data-departure-preset]')).toBeNull()
  expect(document.getElementById('departureSummary')?.textContent).toContain('역까지 10분')
  expect(document.querySelector('#departureSummary button')).toBeNull()
  expect(document.getElementById('departureSummary')?.textContent).toContain('로그인하면 마이페이지에서 예상 이동시간을 설정할 수 있어요.')
})

it.each(['standard', 'resting'])('마이페이지에서 간단 선택 %s를 저장하면 네 구간이 채워져 계산과 openTime에 전달된다', async (presetId) => {
  vi.spyOn(window.ApiClient, 'isApiMode').mockReturnValue(true)
  const calculate = vi.spyOn(window.TimeCalculator, 'calculateDepartureLive').mockResolvedValue(result('09:20'))
  render(<App />)
  loginMypage()
  fireEvent.click(document.querySelector(`[data-departure-preset="${presetId}"]`)!)
  const expected = window.TimeCalculator.getDeparturePresets().find((option) => option.id === presetId)!.minutes
  expect(document.querySelectorAll('[data-departure-preset][aria-pressed="true"]')).toHaveLength(1)
  saveMinutes()
  goTab('time')
  open()
  await waitFor(() => expect(calculate).toHaveBeenCalledOnce())
  expect(calculate.mock.lastCall?.[0]).toMatchObject(expected)
  open('gyodae')
  await waitFor(() => expect(calculate).toHaveBeenCalledTimes(2))
  expect(calculate.mock.lastCall?.[0]).toMatchObject(expected)
})
